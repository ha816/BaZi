def build_saju_character(natal: NatalInfo) -> dict:
    """일간 × 신강/신약 → 캐릭터 유형 (그림 키·이름·유형명·한 줄·직업)"""
    stem = natal.saju.stem_of_day_pillar
    strong = natal.is_strong
    name, title, line, job, jobs = _TYPES[(stem.name, strong)]
    return {
        "key": f"{stem.korean}_{'강' if strong else '약'}",
        "stem": stem.name,
        "stem_korean": stem.korean,
        "element": stem.element.name,
        "strong": strong,
        "strength_label": natal.strength_label,
        "strength_pct": natal.strength_pct,
        "name": name,
        "title": title,
        "line": line,
        "job": job,
        "jobs": jobs,
    }
