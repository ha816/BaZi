def level_for(score: int) -> str:
    if score >= 80:
        return "최고"
    if score >= 60:
        return "좋음"
    if score >= 40:
        return "보통"
    if score >= 20:
        return "아쉬움"
    return "주의"


def label_for(score: int, rel: RelationType) -> str:
    for threshold, text in TOTAL_LABEL_BY_REL[rel]:
        if score >= threshold:
            return text
    return TOTAL_LABEL_BY_REL[rel][-1][1]


