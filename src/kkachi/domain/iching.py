from dataclasses import dataclass


@dataclass(frozen=True)
class Trigram:
    """팔괘(八卦) 하나 — 세 줄(아래→위, True=양)과 오행. 건·태 金, 리 火, 진·손 木, 감 水, 간·곤 土.
    name은 쉬운 뜻 이름(하늘·못…), nature는 전통 괘 이름에 쓰는 글자(천·택·화·뢰·풍·수·산·지)."""
    key: str
    name: str
    hanja: str
    reading: str
    nature: str
    element: str
    lines: tuple[bool, bool, bool]


@dataclass(frozen=True)
class Hexagram:
    """64괘 하나 — 쉬운 뜻 이름(name)과 괘 글자(hanja, 화면엔 괄호 안에만), 위·아래 팔괘 키, 우리 문장.
    문장은 전부 한글(화면 폰트 서브셋 — 한자·영문은 hanja 필드에만, 테스트가 검사).
    now = 본괘로 나왔을 때 "지금" 한 줄, next = 지괘로 올 때 "앞으로" 한 줄, love·work·money = 영역 한 줄."""
    id: int
    key: str
    name: str
    hanja: str
    reading: str
    upper: str
    lower: str
    keywords: tuple[str, str, str]
    now: str
    next: str
    love: str
    work: str
    money: str

    @property
    def lines(self) -> tuple[bool, ...]:
        """여섯 줄 아래→위 — 아래 팔괘 셋 + 위 팔괘 셋."""
        return TRIGRAMS[self.lower].lines + TRIGRAMS[self.upper].lines

    @property
    def traditional(self) -> str:
        """전통 이름 한글 읽기 — 중천건·수뢰둔·뇌지예(첫 글자 두음)."""
        up, low = TRIGRAMS[self.upper], TRIGRAMS[self.lower]
        head = f"중{up.nature}" if up is low else f"{up.nature}{low.nature}"
        if head.startswith("뢰"):
            head = "뇌" + head[1:]
        return head + self.reading


